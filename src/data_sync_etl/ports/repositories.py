from contextlib import AbstractContextManager
from typing import Any, Protocol

from data_sync_etl.ports.search import SearchMetadataReader


class Repository(SearchMetadataReader, Protocol):
    def catalog_page(self, kind: str, *, page: int, size: int, query: str | None = None, source_rows: list[dict] | None = None) -> dict: ...
    def resource_version_summaries(self, resource_ids: list[str]) -> dict[str, dict]: ...
    def evaluation_state(self, filters: dict, *, limit: int, max_units: int) -> str: ...
    def source_metadata_page(self, stream: str, after: str | None, size: int) -> list[dict]: ...
    def metadata_sync_state(self, stream: str, record_id: str) -> dict | None: ...
    def metadata_subject_exists(self, subject_id: str) -> bool: ...
    def master_metadata_page(self, stream: str, after: str | None, size: int) -> list[dict]: ...
    def reserve_master_mongo_identity(self, stream: str, record_id: str, expected: str | None, target: str, *,
                                    dry_run=False, eligible_only=False, expected_origin=None) -> None: ...
    def content_units(self, version_id: str, *, offset=0, limit=50, search="") -> dict: ...
    def get_resource_detail(self, resource_id: str) -> dict | None: ...
    def get(self, table: str, key: Any, *, lock=False) -> dict | None: ...
    def find(
        self,
        table: str,
        filters: dict | None = None,
        *,
        order=(),
        limit=None,
        lock=False,
        skip_locked=False,
    ) -> list[dict]: ...
    def insert(self, table: str, values: dict) -> dict: ...
    def update(self, table: str, key: Any, values: dict) -> None: ...
    def delete(self, table: str, filters: dict) -> None: ...
    def count(self, table: str, filters: dict) -> int: ...
    def ensure_checkpoint(self, stream: str) -> None: ...
    def source_import_page(self, after=None, size=20, retry_candidates=False, failed_only=False) -> list[dict]: ...
    def claim_source_import(self, stamp, token, expires_at) -> dict | None: ...
    def sync_upsert(self, table: str, values: dict, *, source_origin: str | None = None) -> str: ...
    def reconciliation_page(self, table: str, after: str | None, size: int) -> list[dict]: ...
    def ensure_auto_sync_config(self, interval_seconds: int) -> None: ...
    def stale_tasks(self, cutoff) -> list[dict]: ...
    def health(self) -> None: ...
    def index_candidates(self) -> list[dict]: ...
    def list_resources(
            self,
            *,
            keyword: str | None,
            subject_id: str | None,
            grade_level_id: str | None,
            resource_type_code: str | None,
            offset: int,
            limit: int,
            allowed_resource_ids: frozenset[str] | None = None,
    ) -> tuple[list[dict], int]: ...


class UnitOfWork(Protocol):
    def __call__(self) -> AbstractContextManager[Repository]: ...
    def sync_lock(self) -> AbstractContextManager[bool]: ...
    def processing_lock(self, version_id: str) -> AbstractContextManager[bool]: ...
    def metadata_projection_lock(self, stream: str) -> AbstractContextManager[bool]: ...


