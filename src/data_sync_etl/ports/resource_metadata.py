from typing import Any, Protocol
class ResourceMetadataRepository(Protocol):
    def get_resource_for_update(self, resource_id: str) -> dict[str, Any] | None: ...
    def update_resource_metadata(self, resource_id: str, values: dict[str, Any]) -> dict[str, Any]: ...
    def replace_subject_relation(self, resource_id: str, subject_id: str | None) -> None: ...
    def replace_grade_relation(self, resource_id: str, grade_level_id: str | None) -> None: ...
    def get_resource_subject_id(self, resource_id: str) -> str | None: ...
    def get_resource_grade_level_id(self, resource_id: str) -> str | None: ...