"""Independent dense chunk embeddings; deliberately no keyword extraction port."""
from typing import Protocol


class SemanticEmbedding(Protocol):
    dimension: int
    model_revision: str
    batch_size: int

    def model_identity(self) -> dict: ...
    def is_available(self) -> bool: ...
    def prepare(self) -> None: ...
    def require_search_ready(self) -> None: ...
    def embed_documents(self, texts: list[str]) -> list[dict]: ...
    def embed_queries(self, queries: list[str]) -> list[dict]: ...
    def rerank(self, query: str, texts: list[str]) -> list[float]: ...


class SemanticStore(Protocol):
    def ensure_ready(self) -> None: ...
    def manifest(self, index_id: str) -> dict | None: ...
    def claim(self, plan: dict, lease_seconds: int) -> str: ...
    def records(self, index_id: str, limit: int) -> list[dict]: ...
    def save(self, index_id: str, owner: str, record: dict) -> None: ...
    def finish(self, index_id: str, owner: str, status: str, code: str | None = None) -> None: ...
