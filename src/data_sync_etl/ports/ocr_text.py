"""Boundary for OCR and normalized text attached to an active unit of work."""
from typing import Protocol


class OCRTextPort(Protocol):
    def insert_page(self, repo, values): ...
    def page_by_task(self, repo, task_id): ...
    def set_normalized(self, repo, result_id, text, updated_at): ...
    def set_metadata(self, repo, result_id, metadata): ...
    def unit_text(self, repo, unit_id): ...
    def insert_unit_text(self, repo, unit_id, result_id, text): ...
    def update_unit_text(self, repo, unit_id, result_id, text): ...
    def delete_unit_text(self, repo, unit_id): ...


class ComponentOCRContentPort(Protocol):
    """Content store supplied by the server after source authorization."""

    def probe(self, *, authorized, namespace, version_id, generation, source_hash, fingerprint): ...
    def put_page(self, *, namespace, version_id, generation, page_num, source_hash, fingerprint, raw_text,
                 engine_name=None, engine_version=None, confidence=None, result_metadata=None): ...
    def get_page(self, *, namespace, version_id, generation, page_num, source_hash, fingerprint): ...
    def put_unit(self, *, namespace, version_id, generation, unit_id, source_hash, fingerprint, text): ...
    def get_unit(self, *, namespace, version_id, generation, unit_id, source_hash, fingerprint): ...
