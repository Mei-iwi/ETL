from typing import Protocol

from data_sync_etl.ports.mongo_foundation import EmbeddingPort


class IndexEmbeddingPort(EmbeddingPort, Protocol):
    def available(self) -> bool: ...
    def prepare(self) -> None: ...


class IndexStorePort(Protocol):
    def ensure_ready(self) -> None: ...
    def source_units(self, version_id: str, limit: int) -> list[dict]: ...
    def upsert(self, document: dict) -> None: ...
    def artifacts(self, version_id: str, run_id: str, limit: int, offset: int = 0) -> list[dict]: ...
